/// Случайный продукт из [list], отличный от [except].
Food randomFood(Random rnd, List<Food> list, {Food? except}) {
  Food f;
  do {
    f = list[rnd.nextInt(list.length)];
  } while (list.length > 1 && f == except);
  return f;
}